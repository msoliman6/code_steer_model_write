"""The harness figure: how the runtime is wired, the second block diagram in the README. It is
the user's architecture sketch (docs: "Python-First Agent Workflow Dashboard") drawn in the same
glass idiom as the workflow figure: the agent workflow feeds Prefect and MLflow, both feed
monitor.db, then Reflex, the custom dashboard, the browser. The responsibility split that
accompanies the sketch is text in the README, not part of the figure. Generated by code so it
cannot drift (rule 4)."""

from __future__ import annotations

from pathlib import Path
from typing import Literal

from .figure import ARROW, ARROW_W, FONT, LIGHT_FILL, MUTED, TEXT, W, Box, _box_style, _esc

Theme = Literal["dark", "light"]

LEAD = 23.0  # line height inside a box
PAD = 26.0  # top and bottom padding inside a box


def _h(lines: list[str]) -> float:
    return PAD * 2 + LEAD * (len(lines) - 1)


# (kind, x, w, lines) in reading order; y is computed from the gaps
PREFECT = [
    "PREFECT",
    "Python SDK",
    "",
    "orchestration",
    "flow/task state",
    "dependencies",
    "retries",
    "failures",
    "scheduling",
    "cancellation",
]
MLFLOW = [
    "MLFLOW",
    "Python SDK",
    "",
    "agent traces",
    "spans",
    "LLM calls",
    "tool calls",
    "retrieval",
    "tokens / cost",
    "latency",
    "evaluations",
    "ML experiments",
    "params / metrics",
    "artifacts/models",
]
MONITOR = [
    "monitor.db",
    "SQLite",
    "",
    "dashboard-only state",
    "- agent progress",
    "- current activity",
    "- UI labels",
    "- custom messages",
    "- graph positions",
    "- selected run state",
]
REFLEX = [
    "REFLEX",
    "Python App",
    "",
    "task creation",
    "run controls",
    "live monitoring",
    "traces",
    "experiments",
    "evaluations",
    "artifacts",
]
DASHBOARD = [
    "CUSTOM DASHBOARD",
    "",
    "Overview",
    "Workflow DAG",
    "Agent status",
    "MLflow traces",
    "Experiments",
    "Evaluations",
    "Artifacts",
    "Costs / tokens",
    "Live activity",
    "Errors",
]
GAP = 44.0  # between rows, room for a 34px arrow and its gaps


def layout() -> list[Box]:
    boxes: list[Box] = []
    y = 30.0
    top = ["AGENT WORKFLOW", "Python"]
    boxes.append(Box(60, y, 880, _h(top), "code", top, weight=700, size=20))
    y += _h(top) + GAP
    hp, hm = _h(PREFECT), _h(MLFLOW)
    boxes.append(Box(130, y, 320, hp, "code", PREFECT, weight=700, size=20))
    boxes.append(Box(550, y, 320, hm, "both", MLFLOW, weight=700, size=20))
    y += max(hp, hm) + GAP
    for kind, lines in (("both", MONITOR), ("you", REFLEX), ("you", DASHBOARD)):
        boxes.append(Box(300, y, 400, _h(lines), kind, lines, weight=700, size=20))
        y += _h(lines) + GAP
    boxes.append(Box(390, y, 220, 50, "output", ["Browser"], weight=600, size=19))
    return boxes


def render(theme: Theme = "dark", names: dict[str, str] | None = None) -> str:  # noqa: ARG001
    text, muted, arrow, aw = TEXT[theme], MUTED[theme], ARROW[theme], ARROW_W[theme]
    boxes = layout()
    H = int(boxes[-1].y + boxes[-1].h + 30)
    L = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="{FONT}">',
        "<defs>",
        f'<marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{arrow}"/></marker>',
        "</defs>",
    ]
    if theme == "light":
        L.append(f'<rect width="{W}" height="{H}" rx="22" fill="#ffffff"/>')
    else:
        L.append("<!-- transparent canvas: the host page's dark ground shows through -->")
    for b in boxes:
        fill, stroke, sw = _box_style(b, theme)
        if theme == "light" and b.kind in ("a", "b", "you", "both", "code"):
            fill = LIGHT_FILL[b.kind]
        stroke_attr = f' stroke="{stroke}" stroke-width="{sw}"' if stroke != "none" else ""
        L.append(
            f'<rect x="{b.x:g}" y="{b.y:g}" width="{b.w:g}" height="{b.h:g}" rx="14" fill="{fill}"{stroke_attr}/>'
        )
        n = len(b.lines)
        for i, ln in enumerate(b.lines):
            if not ln:
                continue
            cy = b.y + PAD + i * LEAD if n > 1 else b.y + b.h / 2
            title = i == 0
            size = b.size if title else 15
            weight = b.weight if title else 500
            col = text if (title or i == 1 and b.kind == "output") else (muted if i >= 2 else text)
            L.append(
                f'<text x="{b.x + b.w / 2:g}" y="{cy:.1f}" text-anchor="middle" dominant-baseline="central" font-size="{size}" font-weight="{weight}" fill="{col}">{_esc(ln)}</text>'
            )
    # arrows: workflow -> prefect and mlflow (fan-out), both -> monitor.db (fan-in), then the spine
    top, pre, ml, mon, ref, dash, browser = boxes

    def seg(x1, y1, x2, y2):
        L.append(
            f'<line x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}" stroke="{arrow}" stroke-width="{aw}" stroke-linecap="round" marker-end="url(#ah)"/>'
        )

    cx = top.x + top.w / 2
    yb = top.y + top.h + 2
    for b in (pre, ml):
        seg(cx, yb, b.x + b.w / 2, b.y - 2)
    ym = mon.y - 2
    for b in (pre, ml):
        seg(b.x + b.w / 2, b.y + b.h + 2, mon.x + mon.w / 2, ym)
    for a, b in ((mon, ref), (ref, dash), (dash, browser)):
        seg(a.x + a.w / 2, a.y + a.h + 2, b.x + b.w / 2, b.y - 2)
    L.append("</svg>")
    return "\n".join(L) + "\n"


def write(out: Path, theme: Theme = "dark") -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(theme), encoding="utf-8")
    return out
